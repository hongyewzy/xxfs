/**
 * 获取字笔画
 */
function getStroke(char) {
  return STROKES_DICT[char] || char.length
}

/**
 * 计算五格
 */
function calcWuge(name) {
  // 去除空格
  name = name.replace(/\s/g, '')
  const chars = name.split('')
  const strokes = chars.map(c => getStroke(c))

  let tianGe, renGe, diGe, waiGe, zongGe

  if (chars.length === 1) {
    // 单字名
    tianGe = strokes[0] + 1
    renGe = strokes[0] + 1
    diGe = 1
    waiGe = 2
    zongGe = strokes[0]
  } else if (chars.length === 2) {
    // 双字名
    tianGe = strokes[0] + 1
    renGe = strokes[0] + strokes[1]
    diGe = strokes[1] + 1
    waiGe = 2
    zongGe = strokes[0] + strokes[1]
  } else {
    // 三字及以上
    tianGe = strokes[0] + 1
    renGe = strokes[0] + strokes[1]
    diGe = strokes.slice(1).reduce((a, b) => a + b, 0)
    waiGe = strokes.slice(2).reduce((a, b) => a + b, 1)
    zongGe = strokes.reduce((a, b) => a + b, 0)
  }

  // 计算五行
  const getWuxing = num => WUXING_MAP[num % 10] || WUXING_MAP[0]

  return {
    tianGe: { num: tianGe, wuxing: getWuxing(tianGe) },
    renGe: { num: renGe, wuxing: getWuxing(renGe) },
    diGe: { num: diGe, wuxing: getWuxing(diGe) },
    waiGe: { num: waiGe, wuxing: getWuxing(waiGe) },
    zongGe: { num: zongGe, wuxing: getWuxing(zongGe) }
  }
}

/**
 * 计算三才配置
 */
function calcSancai(wuge) {
  return wuge.tianGe.wuxing + wuge.renGe.wuxing + wuge.diGe.wuxing
}

/**
 * 获取五格吉凶
 */
function getWugeJixiong(type, num) {
  const jixiong = WUGE_JIXIONG[type]
  if (jixiong.good.includes(num % 81 || 81)) return '吉'
  if (jixiong.bad.includes(num % 81 || 81)) return '凶'
  return '中'
}

/**
 * 获取三才吉凶
 */
function getSancaiJixiong(sancai) {
  return SANCAI_JIXIONG[sancai] || '中'
}

/**
 * 综合评分
 */
function scoreName(name) {
  const wuge = calcWuge(name)
  const sancai = calcSancai(wuge)
  let score = 60

  // 五格评分
  const types = ['tianGe', 'renGe', 'diGe', 'waiGe', 'zongGe']
  types.forEach(type => {
    const jixiong = getWugeJixiong(type, wuge[type].num)
    if (jixiong === '吉') score += 6
    else if (jixiong === '凶') score -= 6
    else score += 2
  })

  // 三才评分
  const sancaiJixiong = getSancaiJixiong(sancai)
  if (sancaiJixiong === '大吉') score += 15
  else if (sancaiJixiong === '吉') score += 10
  else if (sancaiJixiong === '中吉') score += 5
  else if (sancaiJixiong === '凶') score -= 10

  return Math.min(100, Math.max(0, score))
}

/**
 * 分析姓名
 */
function analyzeName(name) {
  const wuge = calcWuge(name)
  const sancai = calcSancai(wuge)

  return {
    name,
    strokes: name.split('').map(c => ({ char: c, stroke: getStroke(c) })),
    wuge: {
      tianGe: { ...wuge.tianGe, jixiong: getWugeJixiong('tianGe', wuge.tianGe.num) },
      renGe: { ...wuge.renGe, jixiong: getWugeJixiong('renGe', wuge.renGe.num) },
      diGe: { ...wuge.diGe, jixiong: getWugeJixiong('diGe', wuge.diGe.num) },
      waiGe: { ...wuge.waiGe, jixiong: getWugeJixiong('waiGe', wuge.waiGe.num) },
      zongGe: { ...wuge.zongGe, jixiong: getWugeJixiong('zongGe', wuge.zongGe.num) }
    },
    sancai: { config: sancai, jixiong: getSancaiJixiong(sancai) },
    score: scoreName(name)
  }
}

